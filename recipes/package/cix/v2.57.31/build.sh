#
# v2.57.31: a console session joins the container's cgroup.
#
# The procfuse binds were never failing -- every container has all six.
# These files are answered from the READER's own cgroup, and exec.c
# joined a container's namespaces with setns() but never its cgroup, so
# a console saw the bound files and read the HOST's numbers out of
# them. htop in the dashboard reported 7.71 GiB against a 1 GiB limit.
# Measured in one container: its own process reads MemTotal 1048576 kB
# and 1 processor; the daemon reading the same files gets 8084416 kB
# and 2. The session now writes "0" into cgroup.procs before execve,
# through an fd opened before any setns().
#
# Also fixes v2.57.30's own bind counter, which read the child's mount
# table while the child was still building it and then froze that
# number -- a false "1 of 6" on every API-created container. Counted
# live from the kernel now.
#
