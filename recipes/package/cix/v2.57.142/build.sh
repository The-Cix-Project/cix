#
# v2.57.142: registry_remove() can no longer kill a running container
# (ADR-0285, #448).
#
# The control plane on .103 froze for 637 seconds and needed a
# hypervisor reset. The chain was handle_rolling_restart_timer_event ->
# registry_remove -> registry_mark_exited -> container_wait ->
# waitid(P_PIDFD, WEXITED): a blocking wait on the one thread that also
# serves HTTP. A pkg install into an image rolls every container
# following it, so an ordinary install could take the box out.
#
# ADR-0180 had already built the asynchronous teardown after this same
# wait froze the control plane twice, moved DELETE and stop onto it,
# and left the synchronous kill-and-reap for ten other reactor callers
# -- each guarded by a comment arguing its entry could not be running.
# Three were wrong: the rolling restart, pkg cancel, and
# storage-migration finalize.
#
# registry_remove() now releases the slot of a container that has
# already exited and nothing else, polling the pidfd rather than
# trusting e->running, and refusing with EBUSY when the container is
# genuinely alive. The three callers move behind two new teardown
# kinds, RESTART and MIGRATE. pkg cancel's hand-written completion
# block is deleted rather than moved -- it existed only because the
# synchronous kill meant the exit never reached the pidfd handler.
#
# Also carried, from the two commits before this tag: cixd always binds
# loopback (ADR-0284) and the management address lives only in net.conf
# (#443) -- neither has been on a running box yet.
#
