/*
 * test_web_form -- the generated form is RUN, not just parsed.
 *
 * `web/form.js` turns a field the contract describes into the one
 * control that field's own constraints call for (ADR-0338, #595), and
 * until this existed the only gate over it was `test_web_syntax`, which
 * proves a file parses. That distinction is not academic here: three
 * releases in one day shipped a `web/api.js` that parsed every
 * assertion put to it and would not load in a browser (#594), and the
 * check that caught them was the one that handed the file to a real
 * engine.
 *
 * So this hands the engine the real generated `web/api.js` and the real
 * `web/form.js`, over a DOM small enough to write down, and asserts
 * what an operator would otherwise have to open the dashboard to see:
 *
 *   - a field the contract marks `format: password` renders obscured,
 *     which is the whole reason those eight fields carry it;
 *   - an `enum` renders as a select carrying exactly its own values,
 *     in contract order;
 *   - a numeric field carries the contract's own minimum and maximum,
 *     so a form refuses what the daemon would refuse;
 *   - an empty optional field is OMITTED from the body rather than sent
 *     as "", because every partial-update endpoint here reads an absent
 *     key as "leave it alone";
 *   - a boolean is a checkbox and arrives as a boolean, not as "on";
 *   - a field the contract marks `x-cix-ui: textarea`, and any field
 *     typed `object`, renders multi-line -- and every `ui` value in
 *     the whole generated surface is one this renderer knows, which
 *     is the half of that pair apigen cannot gate;
 *   - a free-form object round-trips as JSON and a mistyped one is
 *     refused by name rather than sent;
 *   - a `fixed` field -- the key of an upsert addressing something
 *     that already exists -- renders read-only and is still SENT.
 *
 * The DOM shim is deliberately the smallest thing form.js actually
 * uses. It is not a browser, and a test that needed more of one would
 * be a sign the renderer had grown a dependency it should not have.
 */
